// A Tabler site as one SWI-Prolog program: the tables as facts, formula columns, reports and
// pages, served as HTML by SWI-Prolog's own web server. Forms add rows, which are kept in
// tabler_data.pl beside the program, so they survive a restart. Run it with:
//   swipl site.pl 8095        then open http://localhost:8095/
import { fill, parseFormula, slugOf } from './db.js';

// ------------------------------------------------------------------ writing Prolog terms
export const atom = (s) => `'${String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const value = (v, type) => {
  if (type === 'number') { const n = Number(v); return v !== '' && v !== null && v !== undefined && Number.isFinite(n) ? String(n) : "''"; }
  return atom(v ?? '');
};
const list = (xs) => `[${xs.join(', ')}]`;
function formulaTerm(tree) {
  if ('num' in tree) return String(tree.num);
  if ('col' in tree) return atom(tree.col);
  if (tree.op === 'neg') return `-(${formulaTerm(tree.a)})`;
  return `(${formulaTerm(tree.a)}${tree.op}${formulaTerm(tree.b)})`;
}

export function siteProgram(site, { port = 8095 } = {}) {
  const vars = site.variables ?? {};
  const lines = [];
  const add = (...l) => lines.push(...l);
  add(`% ${site.name ?? 'Tabler site'}: generated by Tabler (Lucian Office). Edit it in Tabler, not here.`,
    `% Run: swipl ${slugOf(site.name)}.pl ${port}   then open http://localhost:${port}/`, '');
  add(':- use_module(library(http/thread_httpd)).', ':- use_module(library(http/http_dispatch)).', ':- use_module(library(http/html_write)).',
    ':- use_module(library(http/http_parameters)).', ':- use_module(library(lists)).', ':- use_module(library(apply)).', ':- use_module(library(pairs)).', '');
  add(':- dynamic row/3.', ':- discontiguous column/5, row/3, report/9, page/3.', ':- initialization(main, main).', '');
  add(`site_name(${atom(fill(site.name, vars))}).`, `default_port(${Number(port)}).`, '');
  for (const [k, v] of Object.entries(vars)) add(`variable(${atom(k)}, ${atom(v)}).`);
  add('');
  // tables
  for (const t of site.tables) {
    add(`% table ${t.name}`);
    t.columns.forEach((c, i) => {
      const f = c.formula ? `formula(${formulaTerm(parseFormula(c.formula, t.columns.filter((x) => x !== c)).tree)})` : 'none';
      add(`column(${atom(t.name)}, ${i + 1}, ${atom(c.name)}, ${c.type === 'number' ? 'number' : 'text'}, ${f}).`);
    });
    (t.rows ?? []).forEach((r, i) => {
      const pairs = t.columns.filter((c) => !c.formula).map((c) => `${atom(c.name)}-${value(r[c.name], c.type)}`);
      add(`row(${atom(t.name)}, ${i + 1}, ${list(pairs)}).`);
    });
    add('');
  }
  // reports
  for (const r of site.reports ?? []) {
    const t = site.tables.find((x) => x.name === r.table);
    const typeOf = (col) => t?.columns.find((c) => c.name === col)?.type ?? 'text';
    const wheres = (r.where ?? []).map((w) => `where(${atom(w.column)}, ${atom(w.op)}, ${typeOf(w.column) === 'number' && w.op !== 'contains' && Number.isFinite(Number(w.value)) ? Number(w.value) : atom(w.value)})`);
    const measures = (r.measures ?? []).map((m) => `${atom(m.fn)}-${atom(m.column ?? '')}`);
    const sort = r.sort?.by ? `sort(${atom(r.sort.by)}, ${r.sort.desc ? 'desc' : 'asc'})` : 'none';
    add(`report(${atom(r.name)}, ${atom(r.title ?? r.name)}, ${atom(r.table)}, ${list(wheres)}, ${atom(r.groupBy ?? '')}, ${list(measures)}, ${sort}, ${Number(r.limit ?? 0)}, ${list((r.columns ?? []).map(atom))}).`);
  }
  add('');
  // pages
  site.pages.forEach((p) => {
    const sections = p.sections.map((s) => {
      if (s.kind === 'text') return `text(${atom(fill(s.text, vars))})`;
      if (s.kind === 'heading') return `heading(${atom(fill(s.text, vars))})`;
      if (s.kind === 'table') return `table(${atom(s.table)}, ${list((s.columns ?? []).map(atom))})`;
      if (s.kind === 'report') return `report(${atom(s.report)})`;
      if (s.kind === 'form') return `form(${atom(s.table)}, ${list((s.columns ?? []).map(atom))}, ${atom(fill(s.thanks ?? 'Thank you.', vars))})`;
      if (s.kind === 'variable') return `variable(${atom(s.name)})`;
      return `text('')`;
    });
    add(`page(${atom(p.slug)}, ${atom(fill(p.title, vars))}, ${list(sections)}).`);
  });
  add('');
  add(...HANDLERS(site.pages.map((p) => p.slug)));
  add(RUNTIME);
  return lines.join('\n') + '\n';
}

const HANDLERS = (slugs) => [
  '% one address per page; the first page is also the home page',
  `:- http_handler(root(.), page_handler(${atom(slugs[0])}), []).`,
  ...slugs.map((s) => `:- http_handler(root(${atom(s)}), page_handler(${atom(s)}), []).`),
  ':- http_handler(root(add), add_row_handler, [method(post)]).',
  ''
];

// The part every site shares: values and formulas, reports, HTML, forms and saving.
const RUNTIME = String.raw`
main :-
    current_prolog_flag(argv, Argv),
    ( member(A, Argv), atom_number(A, Port) -> true ; default_port(Port) ),
    load_data,
    http_server(http_dispatch, [port(Port)]),
    format("Tabler site on http://localhost:~w/~n", [Port]),
    thread_get_message(_).

% ---- values: a stored value, or a formula worked out from the row's other columns
value(T, Id, Col, V) :-
    column(T, _, Col, _, formula(F)), !,
    eval_formula(F, T, Id, V).
value(T, Id, Col, V) :-
    row(T, Id, Pairs),
    ( memberchk(Col-V0, Pairs) -> V = V0 ; V = '' ).

eval_formula(N, _, _, N) :- number(N), !.
eval_formula(C, T, Id, V) :- atom(C), !, value(T, Id, C, V0), ( number(V0) -> V = V0 ; V = nan ).
eval_formula(-(A), T, Id, V) :- !, eval_formula(A, T, Id, X), ( number(X) -> V is -X ; V = nan ).
eval_formula(E, T, Id, V) :-
    E =.. [Op, A, B],
    eval_formula(A, T, Id, X), eval_formula(B, T, Id, Y),
    (   number(X), number(Y), \+ ( Op == (/), Y =:= 0 )
    ->  E2 =.. [Op, X, Y], V is E2
    ;   V = nan
    ).

% ---- reports: filter, group (keeping the order groups first appear in), summarise, sort
report_result(Name, Title, Header, Rows) :-
    report(Name, Title, T, Wheres, Group, Measures, Sort, Limit, Cols),
    findall(Id, ( row(T, Id, _), maplist(where_ok(T, Id), Wheres) ), Ids),
    (   Group \== ''
    ->  findall(K-Id, ( member(Id, Ids), value(T, Id, Group, K) ), KIs),
        group_keys(KIs, Groups),
        ( Measures == [] -> Ms = [count-''] ; Ms = Measures ),
        maplist(measure_label, Ms, Labels),
        Header = [Group|Labels],
        findall([K|Vs], ( member(K-GIds, Groups), maplist(measure_value(T, GIds), Ms, Vs) ), Rows0)
    ;   Measures \== []
    ->  maplist(measure_label, Measures, Header),
        maplist(measure_value(T, Ids), Measures, Vs),
        Rows0 = [Vs]
    ;   ( Cols == [] -> findall(C, column(T, _, C, _, _), Header) ; Header = Cols ),
        findall(Vs, ( member(Id, Ids), findall(V, ( member(C, Header), value(T, Id, C, V) ), Vs) ), Rows0)
    ),
    sort_rows(Sort, Header, Rows0, Rows1),
    limit_rows(Limit, Rows1, Rows).

where_ok(T, Id, where(C, Op, W)) :- value(T, Id, C, V), compare_op(Op, V, W).

compare_op(Op, V, W) :- Op \== contains, number(V), number(W), !, num_op(Op, V, W).
compare_op(Op, V, W) :- format(string(SV), "~w", [V]), format(string(SW), "~w", [W]), str_op(Op, SV, SW).
num_op('=', V, W) :- V =:= W.
num_op('!=', V, W) :- V =\= W.
num_op('>', V, W) :- V > W.
num_op('>=', V, W) :- V >= W.
num_op('<', V, W) :- V < W.
num_op('<=', V, W) :- V =< W.
str_op('=', A, B) :- A == B.
str_op('!=', A, B) :- A \== B.
str_op('>', A, B) :- compare(>, A, B).
str_op('>=', A, B) :- \+ compare(<, A, B).
str_op('<', A, B) :- compare(<, A, B).
str_op('<=', A, B) :- \+ compare(>, A, B).
str_op(contains, A, B) :- string_lower(A, LA), string_lower(B, LB), sub_string(LA, _, _, _, LB).

group_keys([], []).
group_keys([K-Id|Rest], [K-[Id|Ids]|Groups]) :-
    partition(same_key(K), Rest, Same, Others),
    pairs_values(Same, Ids),
    group_keys(Others, Groups).
same_key(K, K2-_) :- K2 == K.

measure_label(count-_, count) :- !.
measure_label(Fn-C, L) :- format(atom(L), "~w of ~w", [Fn, C]).

measure_value(_, Ids, count-_, N) :- !, length(Ids, N).
measure_value(T, Ids, Fn-C, V) :-
    findall(X, ( member(Id, Ids), value(T, Id, C, X), number(X) ), Xs),
    ( Xs == [] -> V = '' ; aggregate_values(Fn, Xs, V) ).
aggregate_values(sum, Xs, V) :- sum_list(Xs, V).
aggregate_values(average, Xs, V) :- sum_list(Xs, S), length(Xs, N), V is S / N.
aggregate_values(min, Xs, V) :- min_list(Xs, V).
aggregate_values(max, Xs, V) :- max_list(Xs, V).

sort_rows(none, _, Rows, Rows) :- !.
sort_rows(sort(By, Dir), Header, Rows0, Rows) :-
    (   nth1(I, Header, By)
    ->  findall(K-Row, ( member(Row, Rows0), nth1(I, Row, K) ), Keyed),
        ( Dir == desc -> sort(1, @>=, Keyed, Sorted) ; sort(1, @=<, Keyed, Sorted) ),
        pairs_values(Sorted, Rows)
    ;   Rows = Rows0
    ).

limit_rows(0, Rows, Rows) :- !.
limit_rows(N, Rows, Limited) :-
    length(Rows, Len),
    ( Len =< N -> Limited = Rows ; length(Limited, N), append(Limited, _, Rows) ).

% ---- how values are shown: whole numbers plainly, others to at most 2 decimal places
shown(V, S) :- integer(V), !, format(atom(S), "~d", [V]).
shown(V, S) :- float(V), !,
    R is round(V * 100),
    (   R mod 100 =:= 0 -> I is R // 100, format(atom(S), "~d", [I])
    ;   R mod 10 =:= 0 -> D is R / 100, format(atom(S), "~1f", [D])
    ;   D is R / 100, format(atom(S), "~2f", [D])
    ).
shown(nan, '') :- !.
shown(V, V).

% ---- pages
page_handler(Slug, Request) :-
    page(Slug, Title, Sections),
    ( catch(http_parameters(Request, [added(Added, [optional(true)])]), _, fail) -> true ; true ),
    site_name(Site),
    reply_html_page(title([Title, ' - ', Site]),
        [ \site_style, div(class(site), [ \nav(Slug), h1(Title), \sections(Sections, Added) ]) ]).

site_style -->
    html(style('body{font-family:system-ui,sans-serif;margin:0;background:#f6f5f1;color:#222}.site{max-width:860px;margin:0 auto;padding:16px}nav a{margin-right:14px;color:#3a5a8c;font-weight:600}nav{padding:10px 0;border-bottom:1px solid #ddd}table{border-collapse:collapse;margin:10px 0;background:#fff}th,td{border:1px solid #ddd;padding:5px 10px;text-align:left}th{background:#eef1f6}form p{margin:6px 0}label{display:inline-block;min-width:7em}input{font:inherit;padding:4px}.thanks{color:#2e7d32;font-weight:600}')).

nav(Current) -->
    { findall(S-T, page(S, T, _), Pages), site_name(Site) },
    html(nav([ strong(Site), ' ', \nav_links(Pages, Current) ])).
nav_links([], _) --> [].
nav_links([S-T|Rest], Current) -->
    { page_url(S, U) },
    ( { S == Current } -> html(a([href(U), 'aria-current'(page)], T)) ; html(a(href(U), T)) ),
    nav_links(Rest, Current).

page_url(S, U) :-
    page(First, _, _), !,
    ( S == First -> U = '/' ; atom_concat('/', S, U) ).

sections([], _) --> [].
sections([S|Rest], Added) --> section(S, Added), sections(Rest, Added).

section(text(T), _) --> html(p(T)).
section(heading(T), _) --> html(h2(T)).
section(variable(N), _) --> { ( variable(N, V) -> true ; V = '' ) }, html(p([strong(N), ': ', V])).
section(table(T, Cols0), _) -->
    { ( Cols0 == [] -> findall(C, column(T, _, C, _, _), Cols) ; Cols = Cols0 ),
      findall(Shown, ( row(T, Id, _), findall(S, ( member(C, Cols), value(T, Id, C, V), shown(V, S) ), Shown) ), Rows) },
    data_table(Cols, Rows).
section(report(Name), _) -->
    { report_result(Name, Title, Header, Rows0), maplist(maplist(shown), Rows0, Rows) },
    html(h2(Title)),
    data_table(Header, Rows).
section(form(T, Cols0, Thanks), Added) -->
    { ( Cols0 == [] -> findall(C, column(T, _, C, _, none), Cols) ; Cols = Cols0 ) },
    ( { Added == T } -> html(p(class(thanks), Thanks)) ; [] ),
    html(form([method(post), action('/add')],
              [ input([type(hidden), name(table), value(T)]),
                \form_fields(T, Cols),
                p(input([type(submit), value('Send')])) ])).

form_fields(_, []) --> [].
form_fields(T, [C|Cs]) -->
    { ( column(T, _, C, number, _) -> Type = number ; Type = text ) },
    html(p([ label(for(C), C), ' ', input([type(Type), name(C), id(C), step(any)]) ])),
    form_fields(T, Cs).

data_table(Header, Rows) -->
    html(table([ tr(\cells(th, Header)), \table_rows(Rows) ])).
table_rows([]) --> [].
table_rows([R|Rs]) --> html(tr(\cells(td, R))), table_rows(Rs).
cells(_, []) --> [].
cells(Tag, [C|Cs]) --> { E =.. [Tag, C] }, html(E), cells(Tag, Cs).

% ---- forms add rows, kept in tabler_data.pl so they last
add_row_handler(Request) :-
    http_parameters(Request, [table(T, [atom])], [form_data(Form)]),
    findall(C-V,
            ( column(T, _, C, Type, none),
              ( memberchk(C=Raw, Form) -> true ; Raw = '' ),
              typed(Type, Raw, V) ),
            Pairs),
    ( aggregate_all(max(I), row(T, I, _), Max) -> Id is Max + 1 ; Id = 1 ),
    assertz(row(T, Id, Pairs)),
    save_row(row(T, Id, Pairs)),
    ( page(Slug, _, Sections), memberchk(form(T, _, _), Sections) -> true ; page(Slug, _, _) ),
    page_url(Slug, U),
    format(atom(Back), "~w?added=~w", [U, T]),
    http_redirect(see_other, Back, Request).

typed(number, Raw, V) :- atom_number(Raw, V), !.
typed(number, _, '') :- !.
typed(text, Raw, Raw).

data_file('tabler_data.pl').
save_row(Fact) :-
    data_file(F),
    setup_call_cleanup(open(F, append, S), format(S, "~q.~n", [Fact]), close(S)).
load_data :-
    data_file(F),
    (   exists_file(F)
    ->  setup_call_cleanup(open(F, read, S), read_rows(S), close(S))
    ;   true
    ).
read_rows(S) :-
    read_term(S, T, []),
    (   T == end_of_file -> true
    ;   ( T = row(_, _, _) -> assertz(T) ; true ), read_rows(S)
    ).
`;
