// Funnels: a landing page with a sign-up form, an offer, and thank-you or no-thanks pages,
// edited as they will look (WYSIWYG). Tabler writes the funnel as a terminal Prolog program
// in the patterns vetusiapl2webpl supports: HTML passed through writeln, read_string for each
// field, and a numbered menu for the offer. vetusiapl2webpl turns that into a SWI-Prolog web
// server with one page per step. The funnel records its own visits, sign-ups, checkouts and
// refusals in funnel_events.pl beside the server, so spending and returns can be tracked.

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const atom = (s) => `'${String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ')}'`;
// Field names become Prolog variables (and form field names): capitalised letters and digits.
export const fieldVar = (name) => { const v = String(name).replace(/[^A-Za-z0-9]/g, ''); const w = v ? v[0].toUpperCase() + v.slice(1) : 'Field'; return /^[A-Z]/.test(w) ? w : `F${w}`; };

export function sampleFunnel() {
  return {
    name: 'Meditation course',
    provider: 'stripe',
    paymentLink: 'https://buy.stripe.com/test_00000000',
    price: 49,
    currency: 'AUD',
    adSpend: 0,
    landing: {
      headline: 'Calm in ten minutes a day',
      text: 'A short, practical meditation course for busy people.',
      bullets: ['Ten-minute daily sessions', 'Breathing and focus techniques', 'Lifetime access'],
      fields: [{ name: 'Name', label: 'Your first name' }, { name: 'Email', label: 'Your email' }],
      button: 'Send me the free first lesson'
    },
    offer: {
      headline: 'Get the whole course',
      text: 'Join now for all twelve lessons.',
      yes: 'Yes, I want the course',
      no: 'No thanks, just the free lesson'
    },
    thanks: { headline: 'Thank you!', text: 'Your first lesson is on its way. Complete your purchase here:', pay: 'Pay securely' },
    declined: { headline: 'No problem', text: 'Your free lesson is on its way. You can join any time.' }
  };
}

const money = (f) => `${f.currency === 'USD' || f.currency === 'AUD' || !f.currency ? '$' : `${f.currency} `}${Number(f.price ?? 0).toFixed(Number.isInteger(Number(f.price)) ? 0 : 2)}`;

// The funnel as a terminal Prolog program, ready for vetusiapl2webpl.
export function terminalProgram(f) {
  const out = [];
  const say = (html) => out.push(`    writeln(${atom(html)}),`);
  const fields = (f.landing.fields ?? []).filter((x) => x.name).map((x) => ({ ...x, v: fieldVar(x.name) }));
  if (new Set(fields.map((x) => x.v)).size !== fields.length) throw new Error('two fields have the same name');
  if (fields.some((x) => /password/i.test(x.v))) throw new Error('a funnel field cannot be a password');
  if (!fields.length) throw new Error('the landing page needs at least one field, such as Email');
  const who = fields.find((x) => /email/i.test(x.v))?.v ?? fields[0].v;
  out.push(`% Funnel: ${f.name}. Generated by Tabler (Lucian Office); edit it in Tabler.`,
    '% Convert it to a web server with vetusiapl2webpl:',
    '%   swipl -q -g main -s vetusiapl2webpl/src/vetusia_converter.pl -- funnel.pl -o funnel_web.pl --port 8097',
    '', ':- initialization(main, main).', '', 'main :-');
  out.push('    funnel_record(visit, landing),');
  say(`<h1>${esc(f.landing.headline)}</h1>`);
  if (f.landing.text) say(`<p>${esc(f.landing.text)}</p>`);
  if (f.landing.bullets?.length) say(`<ul>${f.landing.bullets.filter(Boolean).map((b) => `<li>${esc(b)}</li>`).join('')}</ul>`);
  fields.forEach((x, i) => {
    out.push(`    writeln(${atom(`${x.label || x.name}:`)}),`);
    out.push(`    read_string(user, "\\n", "\\r", _, ${x.v}),`);
    if (i === fields.length - 1) out.push(`    funnel_record(signup, [${fields.map((y) => y.v).join(', ')}]),`);
  });
  say(`<h1>${esc(f.offer.headline)}</h1>`);
  if (f.offer.text) say(`<p>${esc(f.offer.text)} ${esc(money(f))}</p>`);
  out.push(`    writeln(${atom(`1. ${f.offer.yes || 'Yes'}`)}),`, `    writeln(${atom(`2. ${f.offer.no || 'No thanks'}`)}),`, "    writeln('Choose 1 or 2:'),",
    '    read_string(user, "\\n", "\\r", _, Choice),', '    (   Choice = "1"', `    ->  funnel_record(checkout, ${who}),`);
  out.push(`        writeln(${atom(`<h1>${esc(f.thanks.headline)}</h1>`)}),`);
  out.push(`        writeln(${atom(`<p>${esc(f.thanks.text)}</p>`)}),`);
  if (f.paymentLink) out.push(`        writeln(${atom(`<p><a href="${esc(f.paymentLink)}">${esc(f.thanks.pay || 'Pay')} ${esc(money(f))}</a></p>`)})`);
  else out[out.length - 1] = out[out.length - 1].replace(/,$/, '');
  out.push('    ;   Choice = "2"', `    ->  funnel_record(declined, ${who}),`);
  out.push(`        writeln(${atom(`<h1>${esc(f.declined.headline)}</h1>`)}),`);
  out.push(`        writeln(${atom(`<p>${esc(f.declined.text)}</p>`)})`);
  out.push("    ;   writeln('Please choose 1 or 2.')", '    ).', '');
  out.push('% Each step is recorded beside the server, so visits, sign-ups and sales can be counted.',
    'funnel_record(Event, Detail) :-',
    '    get_time(Time),',
    "    setup_call_cleanup(open('funnel_events.pl', append, S),",
    '                       format(S, "funnel_event(~q, ~q, ~q).~n", [Time, Event, Detail]),',
    '                       close(S)).', '');
  return out.join('\n');
}

// The pages as they will look, for the editor's preview (and for checking the program).
export function previewPages(f) {
  const fields = (f.landing.fields ?? []).filter((x) => x.name);
  return [
    { step: 'landing', title: f.landing.headline, html: `<h1>${esc(f.landing.headline)}</h1>${f.landing.text ? `<p>${esc(f.landing.text)}</p>` : ''}${f.landing.bullets?.length ? `<ul>${f.landing.bullets.filter(Boolean).map((b) => `<li>${esc(b)}</li>`).join('')}</ul>` : ''}${fields.map((x) => `<p>${esc(x.label || x.name)}:</p><input type="text" name="${fieldVar(x.name)}">`).join('')}<button>${esc(f.landing.button || 'Next')}</button>` },
    { step: 'offer', title: f.offer.headline, html: `<h1>${esc(f.offer.headline)}</h1>${f.offer.text ? `<p>${esc(f.offer.text)} ${esc(money(f))}</p>` : ''}<p><label><input type="radio" name="Choice" value="1"> ${esc(f.offer.yes)}</label></p><p><label><input type="radio" name="Choice" value="2"> ${esc(f.offer.no)}</label></p><button>Next</button>` },
    { step: 'thanks', title: f.thanks.headline, html: `<h1>${esc(f.thanks.headline)}</h1><p>${esc(f.thanks.text)}</p>${f.paymentLink ? `<p><a href="${esc(f.paymentLink)}">${esc(f.thanks.pay || 'Pay')} ${esc(money(f))}</a></p>` : ''}` },
    { step: 'declined', title: f.declined.headline, html: `<h1>${esc(f.declined.headline)}</h1><p>${esc(f.declined.text)}</p>` }
  ];
}

